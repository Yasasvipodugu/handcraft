/**
 * Translate any string into the active language.
 * Falls back gracefully to the original English text if no translation is found.
 */
export function translateText(lang: SupportedLanguage, text: string): string {
  if (!text || lang === 'en') return text;
  const trimmed = text.trim();
  const langDict = PHRASE_DICTIONARY[lang];
  if (!langDict) return text;

  // 1. Direct match
  if (langDict[trimmed]) {
    return langDict[trimmed];
  }

  // 2. Direct match in TRANSLATIONS object
  const tObj = TRANSLATIONS[lang];
  if (tObj && (tObj as any)[trimmed]) {
    return (tObj as any)[trimmed];
  }

  // 3. Clean without trailing arrows / colons
  const cleanTrimmed = trimmed.replace(/[\s➔→:]+$/g, '').trim();
  if (langDict[cleanTrimmed]) {
    const translated = langDict[cleanTrimmed];
    if (trimmed.endsWith(' ➔') || trimmed.endsWith('➔')) return `${translated} ➔`;
    if (trimmed.endsWith(':')) return `${translated}:`;
    return translated;
  }

  // 4. Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(langDict)) {
    if (k.toLowerCase() === lower) {
      return v;
    }
  }

  return text;
}

